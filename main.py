import streamlit as st
import pandas as pd
import numpy as np

# -----------------------------------
# 페이지 설정
# -----------------------------------

st.set_page_config(
    page_title="서울 연평균 기온",
    page_icon="🌡️",
    layout="wide"
)

st.title("🌡️ 서울 연평균 기온 분석")


# -----------------------------------
# 데이터 불러오기
# -----------------------------------

URL = "https://raw.githubusercontent.com/greatsong/modudata/bb860932644270ad1199f10d3e7670e30231bce4/data/seoul.csv"

df = pd.read_csv(URL, encoding="utf-8-sig")

df["날짜"] = pd.to_datetime(df["날짜"], errors="coerce")
df["평균기온"] = pd.to_numeric(
    df["평균기온"],
    errors="coerce"
)

df = df.dropna(
    subset=["날짜", "평균기온"]
)

df["연도"] = df["날짜"].dt.year

# 2025년까지만 사용
df = df[df["연도"] <= 2025]


# -----------------------------------
# 연평균 기온 계산
# -----------------------------------

all_years = (
    df.groupby("연도")
    .agg(
        mean=("평균기온", "mean"),
        count=("평균기온", "count")
    )
    .reset_index()
)


# 관측일수가 300일 이상인 연도만 사용
연평균 = all_years[
    all_years["count"] >= 300
].rename(
    columns={"mean": "기온"}
)


# -----------------------------------
# 도전 - 직선 대신 곡선을 쓰면
# -----------------------------------

st.subheader("도전 - 직선 대신 곡선을 쓰면")


# 2005년 이전 = 훈련 데이터
학습 = 연평균[
    연평균["연도"] < 2005
].copy()


# 2005년부터 = 테스트 데이터
평가 = 연평균[
    연평균["연도"] >= 2005
].copy()


# -----------------------------------
# 연도를 작은 수로 바꾸기
# -----------------------------------
# 1950년 → 0
# 2005년 → 0.55
# 2050년 → 1.00

x = lambda y: (y - 1950) / 100


# -----------------------------------
# 1차 / 3차 / 9차 회귀
# -----------------------------------

rows = []

for 차수 in [1, 3, 9]:

    # 훈련 데이터로 회귀계수 계산
    계수 = np.polyfit(
        x(학습["연도"]),
        학습["기온"],
        차수
    )

    # 테스트 데이터 예측
    예측값 = np.polyval(
        계수,
        x(평가["연도"])
    )

    # MAE
    평가오차 = np.abs(
        예측값 - 평가["기온"]
    ).mean()

    # 2050년 예측
    예측_2050 = np.polyval(
        계수,
        x(2050)
    )

    rows.append({
        "곡선": (
            "1차 (직선)"
            if 차수 == 1
            else f"{차수}차"
        ),
        "테스트용 데이터의 오차(MAE)": round(
            평가오차,
            2
        ),
        "2050년 예측(℃)": round(
            예측_2050,
            1
        )
    })


# -----------------------------------
# 결과 표
# -----------------------------------

st.dataframe(
    pd.DataFrame(rows),
    hide_index=True,
    use_container_width=True
)


# -----------------------------------
# 훈련 / 테스트 연도 개수
# -----------------------------------

st.write(
    f"훈련용 데이터: **{len(학습)}개 연도**"
)

st.write(
    f"테스트용 데이터: **{len(평가)}개 연도**"
)
