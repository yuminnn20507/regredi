# 도전 - 직선 대신 곡선을 쓰면

st.subheader("도전 - 직선 대신 곡선을 쓰면")

# -----------------------------
# 연평균 기온 데이터 만들기
# -----------------------------

연평균 = df.copy()

연평균["연도"] = 연평균["날짜"].dt.year

연평균 = (
    연평균.groupby("연도")
    .agg(
        기온=("평균기온", "mean"),
        count=("평균기온", "count")
    )
    .reset_index()
)

# 관측일수가 300일 이상인 연도만 사용
연평균 = 연평균[
    연평균["count"] >= 300
].copy()


# -----------------------------
# 2005년 이전 = 학습
# 2005년부터 = 테스트
# -----------------------------

학습 = 연평균[
    연평균["연도"] < 2005
].copy()

평가 = 연평균[
    연평균["연도"] >= 2005
].copy()


# -----------------------------
# 연도를 작은 수로 바꾸기
# 1950년 → 0
# 2005년 → 0.55
# 2050년 → 1.00
# -----------------------------

x = lambda y: (y - 1950) / 100


# -----------------------------
# 1차, 3차, 9차 회귀
# -----------------------------

rows = []

for 차수 in [1, 3, 9]:

    계수 = np.polyfit(
        x(학습["연도"]),
        학습["기온"],
        차수
    )

    # 테스트 데이터 예측
    예측값 = np.polyval(
        계수,
        x(평가["연도"])
    )

    # MAE
    평가오차 = np.abs(
        예측값 - 평가["기온"]
    ).mean()

    # 2050년 예측
    예측_2050 = np.polyval(
        계수,
        x(2050)
    )

    rows.append({
        "곡선": "1차 (직선)" if 차수 == 1 else f"{차수}차",
        "테스트용 데이터의 오차(MAE)": round(평가오차, 2),
        "2050년 예측(℃)": round(예측_2050, 1)
    })


# -----------------------------
# 결과 표
# -----------------------------

st.dataframe(
    pd.DataFrame(rows),
    hide_index=True,
    use_container_width=True
)


# -----------------------------
# 데이터 개수
# -----------------------------

st.caption(
    f"훈련용 {len(학습)}개 연도 · "
    f"테스트용 {len(평가)}개 연도"
)
